#!/usr/bin/env python3
"""
CR123A instead of the CR2450 in the Rev B power path: the load profiles and the converter model of
power_model.py with a CR123A cell. Everything here is an ESTIMATE; nothing was measured.

Cell model: OCV - I*R - b2*ln(1 + I/i_ref), fitted to points read off the graphs of the Panasonic CR123A
datasheet (July 2024, continuous discharge at 20 degC, plateau voltage): 20 mA 2.90 V, 100 mA 2.82 V,
300 mA 2.72 V, 500 mA 2.63 V, 1000 mA 2.52 V. That fit is the "mid" state. There is no published curve of the
CR123A's resistance against depth of discharge or temperature, so the other states are assumptions, taken as
harsh as the coin-cell ones in power_model.py: "late" = 3 x the resistance and 0.15 V less OCV, "eol" = 8 x and
0.30 V less; the temperature factors are the coin-cell TEMPS table (-10 degC: R x 2.5). The datasheet's own cold
point is milder: 0.9 A pulses at -20 degC start at about 2.3 V against 2.6 V at +20 degC.

Usage: python3 cr123a_study.py            # prints the tables and writes results/cr123a_summary.md (~1 min)
"""
import math
import os

import power_model as M

HERE = os.path.dirname(os.path.abspath(__file__))
POINTS = [(0.02, 2.90), (0.1, 2.82), (0.3, 2.72), (0.5, 2.63), (1.0, 2.52)]
NOMINAL_MAH = 1550.0                 # Panasonic CR123A datasheet
STATES = {"fresh": (0.05, 0.8), "mid": (0.0, 1.0), "late": (-0.15, 3.0), "eol": (-0.30, 8.0)}
CASES = [("fresh", "25C"), ("mid", "25C"), ("late", "25C"), ("eol", "25C"), ("fresh", "-10C"), ("mid", "-10C"),
         ("late", "-10C")]
PROFILES = ["poll x5", "report + active mode", "boot", "commissioning nominal", "commissioning pessimistic"]


def fit():
    best = None
    for ocv in (3.00, 3.05, 3.10):
        for r in [x / 100 for x in range(5, 60)]:
            for b2 in [x / 1000 for x in range(5, 120)]:
                for iref in (0.2e-3, 0.5e-3, 1e-3, 2e-3, 5e-3, 10e-3):
                    e = sum((ocv - i * r - b2 * math.log(1 + i / iref) - v) ** 2 for i, v in POINTS)
                    if best is None or e < best[0]:
                        best = (e, ocv, r, b2, iref)
    return best


def cr123(fitted, state, temp):
    _, ocv, r, b2, iref = fitted
    docv_state, k = STATES[state]
    rf, bf, docv, _ = M.TEMPS[temp]
    rr = r * k * rf
    return M.Cell(name="CR123A %s@%s" % (state, temp), ocv=ocv + docv_state - docv, r_ohm=rr * 0.67,
                  r_p1=rr * 0.33, tau1=0.05, b2=b2 * bf * math.sqrt(k), tau2=20.0, i_ref=iref)


def main():
    f = fit()
    e, ocv, r, b2, iref = f
    out = ["# CR123A in the Rev B power path - model results",
           "",
           "**ESTIMATE.** Generated by `hardware/analysis/cr123a_study.py`; nothing was measured. Cell model and "
           "its assumptions: see the docstring of that script.",
           "",
           "## Fit to the Panasonic CR123A discharge curves (20 degC, plateau)",
           "",
           "OCV %.2f V, R %.2f Ohm, b2 %.3f V, i_ref %.1f mA, rms error %.3f V" % (ocv, r, b2, iref * 1e3,
                                                                              math.sqrt(e / len(POINTS))),
           "",
           "| Load | Datasheet graph | Model |", "|---|---|---|"]
    for i, v in POINTS:
        out.append("| %.0f mA | %.2f V | %.2f V |" % (i * 1e3, v, ocv - i * r - b2 * math.log(1 + i / iref)))
    for label, arch in (("85 uF effective input buffer (the MLCCs alone, no C5: the H2W-123 board)", M.single(85)),
                        ("555 uF (with the 470 uF of the CR2450 boards, for comparison)", M.single(555))):
        out += ["", "## " + label, "",
                "Each cell: result, lowest converter input voltage / lowest 3V3 rail voltage.", "",
                "| Cell state | " + " | ".join(PROFILES) + " |", "|---" * (len(PROFILES) + 1) + "|"]
        for state, temp in CASES:
            row = []
            for pk in PROFILES:
                dt = 1e-3 if "commissioning" in pk else 50e-6
                res = M.simulate(arch, [cr123(f, state, temp)], M.PROFILES[pk](), dt=dt, dt_c=M.TEMPS[temp][3])
                row.append("%s %.2f / %.2f V" % ("**RESET**" if res.reset else "ok", res.v_in_min[0], res.v_out_min))
            out.append("| %s, %s | %s |" % (state, temp.replace("C", " degC"), " | ".join(row)))
    out += ["", "## Reference: the CR2450 of the other boards (power_model.py, 555 uF)", "",
            "| Cell state | " + " | ".join(PROFILES) + " |", "|---" * (len(PROFILES) + 1) + "|"]
    for sc in ("fresh 25C", "mid-life 25C", "late 25C", "fresh -10C"):
        row = []
        for pk in PROFILES:
            res = M.run("S", sc, pk, arch=M.single(555))
            row.append("%s %.2f / %.2f V" % ("**RESET**" if res.reset else "ok", res.v_in_min[0], res.v_out_min))
        out.append("| %s | %s |" % (sc, " | ".join(row)))
    bud = M.energy_budget(M.BUDGET_CASES["nominal (SIT 15 s poll, 1 report / 5 min)"], "S")
    i_ua = bud["cells_total_uA"]
    out += ["", "## Lifetime at the nominal load (%.1f uA from the cell, %.1f uA at the 3V3 rail)" % (i_ua, bud["rail_uA"]),
            "",
            "Usable fraction of the nominal capacity: CR2450 50 / 60 / 70 % (reports fail once the cell's resistance "
            "has grown, docs/power_budget.md); CR123A 85 / 90 / 95 % (ASSUMED: the cell carries the bursts until "
            "its voltage collapses). Self-discharge 1 %/year.", "",
            "| Cell | Nominal | Usable (low / mid / high) | Life (low / mid / high) |", "|---|---|---|---|"]
    for name, cap, usable, leak in (("CR2450 with C5 (1 uA leakage)", 620.0, (0.5, 0.6, 0.7), 1.0),
                                    ("CR123A without C5", NOMINAL_MAH, (0.85, 0.90, 0.95), 0.0)):
        ys = [cap * u / ((i_ua + leak) / 1000 * 8760 + 0.01 * cap) for u in usable]
        out.append("| %s | %.0f mAh | %s mAh | %s years |" % (name, cap, " / ".join("%.0f" % (cap * u) for u in usable),
                                                           " / ".join("%.2f" % y for y in ys)))
    text = "\n".join(out) + "\n"
    print(text)
    with open(os.path.join(HERE, "results", "cr123a_summary.md"), "w") as fh:
        fh.write(text)


if __name__ == "__main__":
    main()
